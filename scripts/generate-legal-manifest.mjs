function sha256File(filePath) {
  const buf = fs.readFileSync(filePath)
  return crypto.createHash('sha256').update(buf).digest('hex')
}

function buildManifestSource(entries) {
  const lines = [
    '/**',
    ' * Bundled DREVORA legal document manifest.',
    ' * Generated by scripts/generate-legal-manifest.mjs — do not invent hashes by hand.',
    ' *',
    ' * Application text is based on the supplied DREVORA legal documents.',
    ' * Legal document versions must be updated deliberately.',
    ' * Material changes require a new version and hash.',
    ' * The app does not replace external legal review.',
    ' */',
    '',
    "export type LegalDocumentType =",
    "  | 'customer_terms'",
    "  | 'dpa'",
    "  | 'privacy_policy'",
    "  | 'worker_terms'",
    '',
    "export type LegalAudience = 'customer_admin' | 'worker' | 'both'",
    '',
    "export type LegalAcceptanceRequirement = 'accept' | 'acknowledge' | 'none'",
    '',
    'export type LegalDocumentManifestEntry = {',
    '  type: LegalDocumentType',
    '  title: string',
    '  version: string',
    '  effectiveDate: string',
    '  audience: LegalAudience',
    '  acceptanceRequirement: LegalAcceptanceRequirement',
    '  sourceFile: string',
    '  isCurrent: boolean',
    '  contentHash: string',
    '}',
    '',
    'export const LEGAL_OPERATOR = {',
    "  name: 'Aurimas Jokubaitis, trading as DREVORA',",
    "  structure: 'Sole trader',",
    "  address: '11 Buckenham Way, Thetford, Norfolk, IP24 1ES, United Kingdom',",
    "  email: 'admin@drevora.uk',",
    "  website: 'drevora.app',",
    '} as const',
    '',
    'export const LEGAL_DOCUMENT_MANIFEST = [',
  ]

  for (const entry of entries) {
    lines.push('  {')
    lines.push(`    type: '${entry.type}',`)
    lines.push(`    title: '${entry.title.replace(/'/g, "\\'")}',`)
    lines.push(`    version: '${entry.version}',`)
    lines.push(`    effectiveDate: '${entry.effectiveDate}',`)
    lines.push(`    audience: '${entry.audience}',`)
    lines.push(`    acceptanceRequirement: '${entry.acceptanceRequirement}',`)
    lines.push(`    sourceFile: '${entry.sourceFile}',`)
    lines.push(`    isCurrent: ${entry.isCurrent},`)
    lines.push(`    contentHash: '${entry.contentHash}',`)
    lines.push('  },')
  }

  lines.push('] as const satisfies readonly LegalDocumentManifestEntry[]', '')
  lines.push(
    'export type LegalManifestDocument = (typeof LEGAL_DOCUMENT_MANIFEST)[number]',
    '',
    'export function getLegalManifestEntry(',
    '  type: LegalDocumentType,',
    '): LegalDocumentManifestEntry {',
    '  const entry = LEGAL_DOCUMENT_MANIFEST.find((item) => item.type === type && item.isCurrent)',
    '  if (!entry) {',
    "    throw new Error(`Missing current legal manifest entry for ${type}`)",
    '  }',
    '  return entry',
    '}',
    '',
    'export function getLegalManifestByHash(contentHash: string): LegalDocumentManifestEntry | undefined {',
    '  return LEGAL_DOCUMENT_MANIFEST.find((item) => item.contentHash === contentHash)',
    '}',
    '',
  )

  return lines.join('\n')
}

function loadEntries() {
  return DOCUMENTS.map((doc) => {
    const filePath = path.join(contentDir, doc.sourceFile)
    if (!fs.existsSync(filePath)) {
      throw new Error(`Missing canonical legal file: ${filePath}`)
    }
    return {
      ...doc,
      contentHash: sha256File(filePath),
    }
  })
}

function main() {
  const check = process.argv.includes('--check')
  const entries = loadEntries()
  const next = buildManifestSource(entries)

  if (check) {
    if (!fs.existsSync(outFile)) {
      console.error('legalManifest.ts is missing. Run: node scripts/generate-legal-manifest.mjs')
      process.exit(1)
    }
    const current = fs.readFileSync(outFile, 'utf8')
    if (current !== next) {
      console.error(
        'Legal manifest is out of date. A legal Markdown file changed without updating the manifest.',
      )
      console.error('Run: node scripts/generate-legal-manifest.mjs')
      process.exit(1)
    }
    console.log('Legal manifest OK')
    for (const entry of entries) {
      console.log(`  ${entry.type} v${entry.version} ${entry.contentHash}`)
    }
    return
  }

  fs.writeFileSync(outFile, next, 'utf8')
  console.log(`Wrote ${path.relative(root, outFile)}`)
  for (const entry of entries) {
    console.log(`  ${entry.type} v${entry.version} ${entry.contentHash}`)
  }
}

main()
