/**
 * Generates / verifies SHA-256 hashes for bundled DREVORA legal Markdown.
 *
 * Application text is based on the supplied DREVORA legal documents.
 * Legal document versions must be updated deliberately.
 * Material changes require a new version and hash.
 * The app does not replace external legal review.
 *
 * Usage:
 *   node scripts/generate-legal-manifest.mjs           # write legalManifest.ts
 *   node scripts/generate-legal-manifest.mjs --check    # fail if out of date
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const contentDir = path.join(root, 'src', 'content', 'legal')
const outFile = path.join(contentDir, 'legalManifest.ts')

